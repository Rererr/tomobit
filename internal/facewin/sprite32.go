// Breed selects which dog the window draws — a knob, never derived
// (ADR-0020 Decision 5: 外見の好みは導出できない数字).
type Breed int

const (
	BreedShiba Breed = iota
	BreedRetriever
	BreedPom
)

// ParseBreed maps the --breed flag values from ADR-0020's knob list.
func ParseBreed(s string) (Breed, bool) {
	switch s {
	case "shiba":
		return BreedShiba, true
	case "retriever":
		return BreedRetriever, true
	case "pom":
		return BreedPom, true
	}
	return 0, false
}

